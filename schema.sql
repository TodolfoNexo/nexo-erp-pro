create extension if not exists pgcrypto;

create type public.app_role as enum ('admin', 'manager', 'operator', 'finance');
create type public.movement_type as enum ('in', 'out', 'adjustment');
create type public.document_status as enum ('draft', 'open', 'paid', 'cancelled', 'overdue');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role public.app_role not null default 'operator',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.flavors (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.flavors(name) values
 ('Coco'), ('Melancia'), ('Morango'), ('Maracujá'), ('Maçã verde')
on conflict (name) do nothing;

create table public.customers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  document text,
  phone text,
  email text,
  address text,
  notes text,
  active boolean not null default true,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table public.suppliers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  document text,
  phone text,
  email text,
  notes text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  flavor_id uuid references public.flavors(id),
  sku text unique,
  unit text not null default 'pacote',
  net_weight_g numeric(10,2) default 190,
  min_stock numeric(12,2) not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.stock_movements (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id),
  movement public.movement_type not null,
  quantity numeric(12,2) not null check (quantity > 0),
  reason text not null,
  reference_id uuid,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table public.production_batches (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id),
  batch_code text not null unique,
  produced_quantity numeric(12,2) not null check (produced_quantity >= 0),
  rejected_quantity numeric(12,2) not null default 0 check (rejected_quantity >= 0),
  production_date date not null default current_date,
  notes text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  check (rejected_quantity <= produced_quantity)
);

create table public.sales_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_id uuid references public.customers(id),
  status public.document_status not null default 'draft',
  order_date date not null default current_date,
  due_date date,
  subtotal numeric(12,2) not null default 0,
  discount numeric(12,2) not null default 0,
  total numeric(12,2) not null default 0,
  notes text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  check (discount >= 0 and total >= 0)
);

create table public.sales_order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.sales_orders(id) on delete cascade,
  product_id uuid not null references public.products(id),
  quantity numeric(12,2) not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  line_total numeric(12,2) generated always as (quantity * unit_price) stored
);

create table public.purchases (
  id uuid primary key default gen_random_uuid(),
  supplier_id uuid references public.suppliers(id),
  description text not null,
  status public.document_status not null default 'open',
  purchase_date date not null default current_date,
  due_date date,
  total numeric(12,2) not null default 0 check (total >= 0),
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table public.financial_entries (
  id uuid primary key default gen_random_uuid(),
  entry_type text not null check (entry_type in ('receivable','payable')),
  description text not null,
  party_name text,
  amount numeric(12,2) not null check (amount >= 0),
  due_date date,
  paid_at timestamptz,
  status public.document_status not null default 'open',
  related_sale_id uuid references public.sales_orders(id),
  related_purchase_id uuid references public.purchases(id),
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

